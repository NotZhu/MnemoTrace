// 从原脑形插画取样的点线颜色，保留上方和右侧较亮、文字后方较暗的明暗关系。
// 按坐标索引，调整节点顺序不会串色；原图仅作校色参考，不参与页面绘制。
function luminance(color: string) {
  const rgb = [1, 3, 5].map(index => {
    const value = parseInt(color.slice(index, index + 2), 16) / 255
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4
  })
  return rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722
}

const backgroundLuminance = luminance('#12171f')

const MIN_EDGE_CONTRAST = 3
export function edgeStroke(color: string) {
  const contrast = (value: string) => (luminance(value) + 0.05) / (backgroundLuminance + 0.05)
  if (contrast(color) >= MIN_EDGE_CONTRAST) return color
  const source = [1, 3, 5].map(index => parseInt(color.slice(index, index + 2), 16))
  const tint = [89, 111, 137]
  const mix = (amount: number) => '#' + source.map((value, index) => Math.round(value + (tint[index] - value) * amount).toString(16).padStart(2, '0')).join('')
  // 仅抬高暗线的底色；保留原有亮线与色相差异，电流出现前就能辨认传播路径。
  let low = 0, high = 1
  for (let turn = 0; turn < 12; turn++) {
    const amount = (low + high) / 2
    if (contrast(mix(amount)) >= MIN_EDGE_CONTRAST + 0.05) high = amount
    else low = amount
  }
  return mix(high)
}

export function hasVisibleStroke(color: string | undefined) {
  // 拓扑仍由原始取样决定；显示层的亮度保底不得重新加入已排除的隐形连接。
  return !!color && (luminance(color) + 0.05) / (backgroundLuminance + 0.05) >= 1.14
}

