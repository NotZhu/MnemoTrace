"""从共享模板和页面差异配置生成两个静态落地页。"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {"demo": "demo/index.html", "docs": "docs/index.html"}
SHARED_ASSETS = (
    "brain-circuit.svg", "github.svg", "fonts/OFL.txt", "fonts/README.txt",
    "fonts/mnemo-sans-sc-var.woff2", "fonts/mnemo-serif-sc-var.woff2",
)
SLOT = re.compile(r"^<!-- landing:([a-z_]+) -->\n", re.MULTILINE)
BANNER = "<!-- Generated by scripts/build_landing_pages.py; edit landing/index.html.in and landing/pages.json. -->\n"


def render_page(template: str, slots: dict[str, str]) -> str:
    expected = set(SLOT.findall(template))
    if set(slots) != expected or not all(isinstance(value, str) for value in slots.values()):
        raise ValueError("landing page slots must match the template exactly")
    html = SLOT.sub(lambda match: slots[match.group(1)], template)
    if "<!-- landing:" in html:
        raise ValueError("unresolved landing page slot")
    first, newline, rest = html.partition("\n")
    if first.lower() != "<!doctype html>" or not newline:
        raise ValueError("landing template must begin with the HTML doctype")
    return first + newline + BANNER + rest


def build_pages(root: Path = ROOT) -> dict[Path, str]:
    template = (root / "landing/index.html.in").read_text(encoding="utf-8")
    variants = json.loads((root / "landing/pages.json").read_text(encoding="utf-8"))
    if set(variants) != set(TARGETS):
        raise ValueError("landing configuration must define demo and docs")
    return {root / target: render_page(template, variants[name]) for name, target in TARGETS.items()}


def build_assets(root: Path = ROOT) -> dict[Path, bytes]:
    """Keep published copies byte-identical without a third resource tree."""
    return {
        root / "docs/assets" / name: (root / "demo/assets" / name).read_bytes()
        for name in SHARED_ASSETS
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只检查生成文件是否最新")
    args = parser.parse_args(argv)
    stale = []
    outputs: dict[Path, str | bytes] = dict(build_pages())
    outputs.update(build_assets(ROOT))
    for path, content in outputs.items():
        if path.is_file():
            # Git may check HTML out as CRLF on Windows; binary assets stay exact.
            current = path.read_text(encoding="utf-8") if isinstance(content, str) else path.read_bytes()
            if current == content:
                continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8") if isinstance(content, str) else content)
            print(f"generated {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("stale landing pages: " + ", ".join(stale))
        print("run python scripts/build_landing_pages.py")
        return 1
    print("OK landing pages are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
