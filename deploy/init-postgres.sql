\getenv app_password MNEMOTRACE_DB_PASSWORD

BEGIN;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

CREATE ROLE mnemotrace_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
    NOREPLICATION NOBYPASSRLS PASSWORD :'app_password';

REVOKE CONNECT, TEMPORARY ON DATABASE mnemotrace FROM PUBLIC;
GRANT CONNECT ON DATABASE mnemotrace TO mnemotrace_app;
CREATE SCHEMA mnemotrace AUTHORIZATION mnemotrace_app;
ALTER ROLE postgres PASSWORD NULL;
COMMIT;
